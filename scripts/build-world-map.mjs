#!/usr/bin/env node
/**
 * Builds src/data/worldMapPaths.ts from Natural Earth 50m country borders (public domain, via the world-atlas package).
 * Run: node scripts/build-world-map.mjs
 *
 * Countries are matched to the app's ISO 3166-1 alpha-2 ids through the numeric ISO code (mledoze/countries).
 * Antarctica is left out so the map is not stretched at the bottom. Coordinates are rounded to one decimal
 * on a canvas about 1000 units wide, which keeps shapes smooth up to the app's maximum zoom.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { geoNaturalEarth1, geoPath } from 'd3-geo';
import { feature } from 'topojson-client';

const require = createRequire(import.meta.url);
const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const topo = require('world-atlas/countries-50m.json');

const countries = await (await fetch('https://raw.githubusercontent.com/mledoze/countries/master/countries.json')).json();
const numericToAlpha2 = new Map(countries.map((c) => [String(Number(c.ccn3)), c.cca2]));
const BY_NAME = { Kosovo: 'XK', Somaliland: 'SOMALILAND', 'N. Cyprus': 'NORTHERN_CYPRUS' };
const SKIP = new Set(['Antarctica', 'Fr. S. Antarctic Lands', 'Indian Ocean Ter.', 'Siachen Glacier']);

const catalogSrc = readFileSync(join(root, 'src/data/travelData.ts'), 'utf8');
const catalogIds = new Set([...catalogSrc.matchAll(/"id": "([A-Z]{2})"/g)].map((m) => m[1]));

const all = feature(topo, topo.objects.countries).features.filter((f) => !SKIP.has(f.properties.name));
const projection = geoNaturalEarth1().fitWidth(1000, { type: 'FeatureCollection', features: all });
const path = geoPath(projection).digits(1);

const out = [];
const unmatched = [];
let minX = Infinity, minY = Infinity, maxX = -Infinity, maxY = -Infinity;
for (const f of all) {
  const id = f.id !== undefined ? numericToAlpha2.get(String(Number(f.id))) : BY_NAME[f.properties.name];
  if (!id) {
    unmatched.push(f.properties.name);
    continue;
  }
  const d = path(f);
  if (!d) continue;
  const [[x0, y0], [x1, y1]] = path.bounds(f);
  minX = Math.min(minX, x0); minY = Math.min(minY, y0); maxX = Math.max(maxX, x1); maxY = Math.max(maxY, y1);
  out.push({ id, d });
}
const missing = [...catalogIds].filter((id) => !out.some((o) => o.id === id));
const bounds = { minX: +minX.toFixed(1), minY: +minY.toFixed(1), width: +(maxX - minX).toFixed(1), height: +(maxY - minY).toFixed(1) };

writeFileSync(
  join(root, 'src/data/worldMapPaths.ts'),
  `// GENERATED by scripts/build-world-map.mjs on ${new Date().toISOString().slice(0, 10)}. Do not edit by hand; rerun the script.
// Natural Earth 50m country borders (public domain), Natural Earth projection.

/** Extent of the artwork in SVG units. */
export const worldBounds = ${JSON.stringify(bounds)};
export const worldViewBox = "${bounds.minX} ${bounds.minY} ${bounds.width} ${bounds.height}";

export const worldMapFeatures: { id: string; d: string }[] = ${JSON.stringify(out)};
`
);
console.log(`countries drawn: ${out.length}, bounds:`, bounds);
console.log('not matched (left out):', unmatched.join(', ') || 'none');
console.log('catalog countries without a shape:', missing.join(', ') || 'none');
