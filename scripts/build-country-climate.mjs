#!/usr/bin/env node
/**
 * Builds src/data/countryClimate.ts. Run: node scripts/build-country-climate.mjs
 *
 * For every catalog country with a capital that has coordinates on Wikidata (CC0), it fetches the monthly
 * climatology (mean temperature, precipitation per day) from NASA POWER, and the capital's IANA time zone
 * from Open-Meteo (CC BY 4.0). Monthly precipitation is the per-day value times the days in the month. The app never calls these services; the numbers ship with it.
 * Values describe the capital only. Large or varied countries differ by region, and the UI says so.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const UA = 'atls-app-data-build/1.0 (contact: emirhancob4n@gmail.com)';
const MONTH_KEYS = ['JAN', 'FEB', 'MAR', 'APR', 'MAY', 'JUN', 'JUL', 'AUG', 'SEP', 'OCT', 'NOV', 'DEC'];
const DAYS = [31, 28.25, 31, 30, 31, 30, 31, 31, 30, 31, 30, 31];
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

async function getJson(url, tries = 6) {
  for (let i = 0; i < tries; i++) {
    const res = await fetch(url, { headers: { 'User-Agent': UA } });
    if (res.ok) return res.json();
    if (res.status === 429 || res.status >= 500) {
      await sleep(20000 * (i + 1));
      continue;
    }
    throw new Error(`${url} -> ${res.status}`);
  }
  throw new Error(`${url} failed after retries`);
}

// Standard (non-daylight-saving) UTC offset in hours: the smaller of the January and July offsets.
function standardOffset(timeZone) {
  const offsetAt = (month) => {
    const d = new Date(Date.UTC(2024, month, 1, 12));
    const parts = new Intl.DateTimeFormat('en-US', { timeZone, timeZoneName: 'longOffset' }).formatToParts(d);
    const raw = parts.find((p) => p.type === 'timeZoneName')?.value || 'GMT';
    const m = raw.match(/GMT([+-])(\d{2}):?(\d{2})?/);
    if (!m) return 0;
    return (m[1] === '-' ? -1 : 1) * (Number(m[2]) + Number(m[3] || 0) / 60);
  };
  return Math.min(offsetAt(0), offsetAt(6));
}

async function main() {
  const catalogSrc = readFileSync(join(root, 'src/data/travelData.js'), 'utf8');
  const ids = [...new Set([...catalogSrc.matchAll(/"id": "([A-Z]{2})"/g)].map((m) => m[1]))];

  console.log('fetching capital coordinates…');
  const sparql =
    'SELECT ?iso ?coord WHERE { ?c wdt:P297 ?iso; wdt:P36 ?cap. FILTER NOT EXISTS { ?c wdt:P576 ?end } ?cap wdt:P625 ?coord. }';
  const wd = await getJson(`https://query.wikidata.org/sparql?format=json&query=${encodeURIComponent(sparql)}`);
  const coords = new Map();
  for (const row of wd.results.bindings) {
    const m = row.coord.value.match(/Point\(([-\d.]+) ([-\d.]+)\)/);
    if (m && !coords.has(row.iso.value)) coords.set(row.iso.value, { lon: Number(m[1]), lat: Number(m[2]) });
  }

  const out = {};
  const missing = [];
  for (const iso of ids) {
    const c = coords.get(iso);
    if (!c) {
      missing.push(iso);
      continue;
    }
    try {
      const power = await getJson(
        `https://power.larc.nasa.gov/api/temporal/climatology/point?parameters=T2M,PRECTOTCORR&community=RE&longitude=${c.lon.toFixed(3)}&latitude=${c.lat.toFixed(3)}&format=JSON`
      );
      const tz = await getJson(
        `https://api.open-meteo.com/v1/forecast?latitude=${c.lat.toFixed(3)}&longitude=${c.lon.toFixed(3)}&daily=temperature_2m_max&forecast_days=1&timezone=auto`
      );
      const t = MONTH_KEYS.map((k) => power.properties.parameter.T2M[k]);
      const perDay = MONTH_KEYS.map((k) => power.properties.parameter.PRECTOTCORR[k]);
      if ([...t, ...perDay].some((v) => typeof v !== 'number' || v < -90)) throw new Error('missing values');
      out[iso] = {
        t: t.map((v) => Math.round(v)),
        p: perDay.map((v, i) => Math.round(v * DAYS[i])),
        tz: tz.timezone,
        utc: standardOffset(tz.timezone),
      };
      process.stdout.write(`${iso} `);
    } catch (err) {
      console.warn(`\n${iso}: ${err.message}`);
      missing.push(iso);
    }
    await sleep(250);
  }
  console.log(`\nmissing: ${missing.join(' ') || 'none'}`);

  const body = Object.entries(out)
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([iso, v]) => `  ${iso}: { t: ${JSON.stringify(v.t)}, p: ${JSON.stringify(v.p)}, tz: ${JSON.stringify(v.tz)}, utc: ${v.utc} },`)
    .join('\n');

  writeFileSync(
    join(root, 'src/data/countryClimate.ts'),
    `// GENERATED by scripts/build-country-climate.mjs on ${new Date().toISOString().slice(0, 10)}. Do not edit by hand; rerun the script.
// Sources: Wikidata (CC0) capital coordinates, NASA POWER monthly climatology, Open-Meteo time zones (CC BY 4.0).
// Values are for the capital city only.

export interface CountryClimate {
  /** Mean daily temperature per month (Jan..Dec), °C. */
  t: number[];
  /** Average total precipitation per month (Jan..Dec), mm. */
  p: number[];
  /** IANA time zone of the capital. */
  tz: string;
  /** Standard (winter) UTC offset in hours. */
  utc: number;
}

export const CLIMATE_META = {
  source: 'NASA POWER climatology, Open-Meteo time zones (CC BY 4.0), Wikidata (CC0)',
};

export const COUNTRY_CLIMATE: Record<string, CountryClimate> = {
${body}
};
`
  );
  console.log(`wrote ${Object.keys(out).length} countries`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
